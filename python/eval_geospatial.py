"""
Stress-tests the geospatial expansion analysis.

geospatial_analysis.py clusters demand-weighted station coordinates and flags KMeans centroids more than 3 km
from the nearest station as "expansion candidates". Three questions decide whether that is a finding or an artifact:

  1. Does demand weighting matter?  Permute the session volumes across stations (breaking any link between
     where a station is and how busy it is) and re-run. If candidates appear just as often, they come from the
     geometry of the station layout, not from demand.
  2. Is demand spatial at all?  Rank-correlate station session volume with distance from the city centre and
     with distance to the nearest other station.
  3. How robust is the flag?  Sensitivity to the distance threshold and to the KMeans seed.

Run (after dbt run):
    python python/eval_geospatial.py
"""
import json

import duckdb
import numpy as np
import pandas as pd
from scipy.stats import spearmanr

import geospatial_analysis as ga
from common import CITIES, DB_PATH, OUT_DIR

N_PERMUTATIONS = 200
SEEDS = range(20)


def flagged_count(stations: pd.DataFrame, threshold_km: float, seed: int = 42) -> int:
    ga.EXPANSION_DISTANCE_THRESHOLD_KM = threshold_km
    n = 0
    for _, grp in stations.groupby("city_key"):
        grp = grp.reset_index(drop=True)
        n_clusters = max(len(grp) // ga.STATIONS_PER_CLUSTER_TARGET, 2)
        weights = (grp["total_sessions"] + 1).to_numpy()
        coords = grp[["latitude", "longitude"]].to_numpy()
        rep = np.repeat(coords, np.ceil(weights / weights.min()).astype(int), axis=0)
        from sklearn.cluster import KMeans
        cents = KMeans(n_clusters=n_clusters, n_init=10, random_state=seed).fit(rep).cluster_centers_
        for lat, lon in cents:
            d = ga.haversine_km(lat, lon, grp["latitude"].to_numpy(), grp["longitude"].to_numpy()).min()
            n += d > threshold_km
    ga.EXPANSION_DISTANCE_THRESHOLD_KM = 3.0
    return int(n)


def main():
    con = duckdb.connect(str(DB_PATH), read_only=True)
    stations = ga.load_data(con)
    con.close()
    rng = np.random.default_rng(0)

    observed = flagged_count(stations, 3.0)

    null = []
    for _ in range(N_PERMUTATIONS):
        perm = stations.copy()
        perm["total_sessions"] = perm.groupby("city_key")["total_sessions"].transform(lambda s: rng.permutation(s.to_numpy()))
        null.append(flagged_count(perm, 3.0))
    null = np.array(null)
    p_value = float((null >= observed).mean())

    # spatial signal in demand
    rows = []
    for city_key, g in stations.groupby("city_key"):
        lat0, lon0 = CITIES[city_key][3], CITIES[city_key][4]
        g = g.assign(dist_centre=ga.haversine_km(g["latitude"], g["longitude"], lat0, lon0))
        rho, p = spearmanr(g["dist_centre"], g["total_sessions"])
        rows.append((city_key, rho, p))
    rho_all = np.array([r[1] for r in rows])
    pooled = stations.assign(dist_centre=[ga.haversine_km(r.latitude, r.longitude, CITIES[r.city_key][3], CITIES[r.city_key][4])
                                          for r in stations.itertuples()])
    pooled_rho, pooled_p = spearmanr(pooled["dist_centre"], pooled["total_sessions"])

    sens = {t: flagged_count(stations, t) for t in (1.0, 2.0, 3.0, 5.0)}
    seeds = [flagged_count(stations, 3.0, seed=s) for s in SEEDS]

    L = ["# Geospatial Analysis Stress Test", "",
         "_Auto-generated by `python/eval_geospatial.py`. Asks whether the 'expansion candidates' reflect demand or just the geometry of the station layout._", "",
         f"Stations: **{len(stations)}** across **{stations['city_key'].nunique()}** cities. "
         f"Observed candidates at 3 km: **{observed}** of {sum(max(len(g) // ga.STATIONS_PER_CLUSTER_TARGET, 2) for _, g in stations.groupby('city_key'))} centroids.", "",
         "## 1. Does demand weighting matter? (permutation null)", "",
         f"Session volumes were shuffled across stations within each city {N_PERMUTATIONS} times (destroying any location-demand link) and the analysis re-run.", "",
         f"- Candidates under the null: mean **{null.mean():.2f}**, 5th-95th percentile **{np.percentile(null, 5):.0f}-{np.percentile(null, 95):.0f}**.",
         f"- Observed: **{observed}**. One-sided permutation p-value: **{p_value:.2f}**.",
         "- " + ("The observed count is typical of the null: the candidates are not explained by demand." if p_value > 0.05
                 else "The observed count is unusual under the null."), "",
         "## 2. Is station demand spatial in this data?", "",
         f"Spearman correlation between a station's session volume and its distance from the city centre: pooled rho = **{pooled_rho:+.2f}** (p = {pooled_p:.2f}); "
         f"per-city rho ranges **{rho_all.min():+.2f} to {rho_all.max():+.2f}** with only {stations.groupby('city_key').size().iloc[0]} stations per city. "
         "In the generator, session volume depends on a station's power rating and connector count, never on its location, so there is no spatial demand to find.", "",
         "## 3. Robustness", "",
         "| Distance threshold | Candidates flagged |", "|---:|---:|"] + [f"| {t:g} km | {v} |" for t, v in sens.items()] + [
         "", f"Across {len(list(SEEDS))} KMeans seeds at 3 km the flagged count ranged **{min(seeds)}-{max(seeds)}** (distinct values: {sorted(set(seeds))}).", "",
         "## Conclusion", "",
         "- Treat the expansion analysis as a **method demonstration** (clustering, haversine coverage, map output), not as evidence about where a real network should expand.",
         "- Station coordinates are synthetic unless `OPENCHARGEMAP_API_KEY` is set, and even with real coordinates, session volumes here do not depend on location.",
         "- A defensible real-world version would need demand observed or modelled *away from existing stations* (population, traffic, failed-session or waiting-time data), "
         "because demand measured at stations can only show where chargers already are."]
    md = "\n".join(L)
    (OUT_DIR / "geospatial_stress_test.json").write_text(json.dumps({
        "observed": observed, "null_mean": float(null.mean()), "null_p5": float(np.percentile(null, 5)), "null_p95": float(np.percentile(null, 95)),
        "p_value": p_value, "pooled_rho": float(pooled_rho), "pooled_p": float(pooled_p), "sensitivity": {str(k): v for k, v in sens.items()}}, indent=2), encoding="utf-8")
    (OUT_DIR / "geospatial_stress_test.md").write_text(md, encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main()
