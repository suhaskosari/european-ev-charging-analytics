"""
Validates the demand-driver regression against the generator's known ground truth.

The published OLS regressed daily sessions on temperature, precipitation, congestion and a weekend flag,
pooled across 8 cities. Two problems:
  1. It ignores city (cities differ in size and climate), so coefficients mix between-city and within-city variation.
  2. The generator's effects are *multiplicative* and the cold effect is a hinge (only below 10 C), so a linear
     temperature term averages a real effect with a zero effect above 10 C and understates it.

This script fits three specifications and compares them to the true parameters in generate_data.py:
  A. Pooled OLS (as originally published)
  B. OLS with city fixed effects and HC3 robust errors
  C. Poisson GLM (log link) with city fixed effects, a cold-degrees hinge, and robust errors

Ground truth, from generate_data.py (per station-day rate = base * weekday_mult * cold_mult * traffic_mult):
  weekend:     log(0.90 / 1.15) = -0.245
  cold hinge:  cold_mult = 1 + 0.015 * max(0, 10 - temp)  -> about +1.5% per degree below 10 C
  congestion:  traffic_mult = 1 + 0.003 * (congestion - 50) -> about +0.3% per index point
  precipitation: no direct effect (it only raises congestion, which has its own effect)

Run (after dbt run):
    python python/eval_demand_model.py
"""
import json

import duckdb
import numpy as np
import pandas as pd
import statsmodels.api as sm
import statsmodels.formula.api as smf
from statsmodels.stats.outliers_influence import variance_inflation_factor
from statsmodels.stats.stattools import durbin_watson

from common import DB_PATH, OUT_DIR

TRUTH = {
    "is_weekend": ("weekend", float(np.log(0.90 / 1.15))),
    "cold_deg": ("cold hinge (per degree below 10 C)", float(np.log(1.015))),
    "congestion_index": ("congestion (per index point)", 0.003),
    "precipitation_mm": ("precipitation (direct effect)", 0.0),
}


def load() -> pd.DataFrame:
    con = duckdb.connect(str(DB_PATH), read_only=True)
    df = con.execute("""
        select city_key, date, sessions_count, temp_avg_c, precipitation_mm, congestion_index, is_weekend
        from main_analytics.city_daily_demand
        where temp_avg_c is not null and congestion_index is not null
    """).df()
    con.close()
    df["date"] = pd.to_datetime(df["date"])
    df["is_weekend"] = df["is_weekend"].astype(int)
    df["precipitation_mm"] = df["precipitation_mm"].fillna(0)
    df["cold_deg"] = (10 - df["temp_avg_c"]).clip(lower=0)
    return df.sort_values(["city_key", "date"]).reset_index(drop=True)


def main():
    df = load()
    mean_sessions = df["sessions_count"].mean()

    a = smf.ols("sessions_count ~ temp_avg_c + precipitation_mm + congestion_index + is_weekend", df).fit()
    b = smf.ols("sessions_count ~ temp_avg_c + precipitation_mm + congestion_index + is_weekend + C(city_key)", df).fit(cov_type="HC3")
    c = smf.glm("sessions_count ~ cold_deg + precipitation_mm + congestion_index + is_weekend + C(city_key)", df,
                family=sm.families.Poisson()).fit(cov_type="HC1")

    # diagnostics on the preferred model
    dispersion = float((c.resid_pearson ** 2).sum() / c.df_resid)
    dw = float(np.mean([durbin_watson(g.assign(r=c.resid_deviance.loc[g.index])["r"].to_numpy())
                        for _, g in df.groupby("city_key")]))
    X = sm.add_constant(df[["cold_deg", "precipitation_mm", "congestion_index", "is_weekend"]])
    vif = {col: float(variance_inflation_factor(X.values, i)) for i, col in enumerate(X.columns) if col != "const"}
    corr_cong_weekend = float(df["congestion_index"].corr(df["is_weekend"].astype(float)))

    L = ["# Demand-Model Validation", "",
         "_Auto-generated by `python/eval_demand_model.py`. Compares regression specifications against the parameters "
         "built into the synthetic generator, so recovery can be checked rather than asserted._", "",
         f"Daily city-level observations: **{len(df):,}** (8 cities). Mean sessions per city-day: **{mean_sessions:.2f}**.", "",
         "## A. The originally published model (pooled OLS, linear temperature)", "",
         "| Driver | Coefficient | Implied % of mean | p-value |", "|---|---:|---:|---:|"]
    for k, v in a.params.items():
        if k != "Intercept":
            L.append(f"| {k} | {v:+.4f} | {v / mean_sessions:+.1%} | {a.pvalues[k]:.2g} |")
    L += ["", "The weekend coefficient lines up with the truth (about -22% of the mean), but the temperature coefficient "
          f"({a.params['temp_avg_c'] / mean_sessions:+.2%} of the mean per degree) is far below the true cold effect (about +1.5% per degree below 10 C) "
          "because a straight line averages the real effect below 10 C with no effect above it. 'Significant' is not the same as 'recovered'.", "",
          "## B. Poisson GLM with city fixed effects (preferred), versus the generator's truth", "",
          "Coefficients are on the log scale, so `exp(coef) - 1` is the percentage change in expected sessions. Robust (HC1) standard errors.", "",
          "| Driver | True value | Estimate | 95% CI | Truth inside CI? | Effect |", "|---|---:|---:|---|:---:|---|"]
    ci = c.conf_int()
    n_inside = 0
    recovery = []
    for var, (label, truth) in TRUTH.items():
        est, lo, hi = c.params[var], ci.loc[var, 0], ci.loc[var, 1]
        inside = lo <= truth <= hi
        n_inside += inside
        recovery.append({"label": label, "truth": truth, "estimate": float(est), "lo": float(lo), "hi": float(hi), "inside": bool(inside)})
        L.append(f"| {label} | {truth:+.4f} | {est:+.4f} | [{lo:+.4f}, {hi:+.4f}] | {'yes' if inside else 'no'} | {np.expm1(est):+.2%} |")
    L += ["", f"The truth falls inside the 95% interval for **{n_inside} of {len(TRUTH)}** parameters.", "",
          "## C. Diagnostics (preferred model)", "",
          f"- Pearson dispersion: **{dispersion:.2f}** (about 1 means Poisson variance is adequate; much above 1 means overdispersion).",
          f"- Durbin-Watson on deviance residuals, mean across cities: **{dw:.2f}** (about 2 means little serial correlation).",
          f"- Correlation between congestion and the weekend flag: **{corr_cong_weekend:.2f}**. The generator makes traffic lighter on weekends, "
          "so congestion partly proxies for weekend and the two coefficients are not cleanly separable in real data.",
          "- Variance inflation factors: " + ", ".join(f"{k} {v:.2f}" for k, v in vif.items()) + ".", "",
          "## Limits", "",
          "- Because the generator builds these effects in, 'recovery' here validates the *method*, not the real-world size of EV demand effects.",
          "- Temperature is real (Open-Meteo archive); traffic and sessions are synthetic. Congestion's effect is therefore an assumption of the generator, "
          "not an empirical finding.",
          "- A real analysis would also need holiday effects, local events and charger outages, none of which exist in this data."]
    md = "\n".join(L)
    (OUT_DIR / "demand_model_validation.json").write_text(json.dumps({
        "recovery": recovery, "n_inside": int(n_inside), "mean_sessions": float(mean_sessions),
        "ols_temp_pct_per_degree": float(a.params["temp_avg_c"] / mean_sessions), "dispersion": dispersion, "durbin_watson": dw,
        "corr_congestion_weekend": corr_cong_weekend}, indent=2), encoding="utf-8")
    (OUT_DIR / "demand_model_validation.md").write_text(md, encoding="utf-8")

    # also refresh the published coefficient table with the corrected specification
    pub = pd.DataFrame({"driver": c.params.index, "coefficient_log_scale": c.params.values,
                        "pct_effect": np.expm1(c.params.values), "p_value": c.pvalues.values})
    pub = pub[~pub["driver"].str.startswith("C(city_key)") & (pub["driver"] != "Intercept")]
    pub.to_csv(OUT_DIR / "demand_drivers_poisson_fe.csv", index=False)
    print(md)


if __name__ == "__main__":
    main()
